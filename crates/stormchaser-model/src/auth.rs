//! Who is asking (claims from a verified token) and what services ask policy. The client
//! that asks is `stormchaser_opa::OpaClient`.

use crate::id::RunId;
use serde::{Deserialize, Serialize};
use serde_json::Value;

/// Extracted claims from a JWT token.
#[derive(Debug, Serialize, Deserialize, Clone)]
pub struct Claims {
    /// Subject (User ID) of the token.
    pub sub: String, // User ID
    /// Optional email address of the user.
    pub email: Option<String>,
    /// Expiration time as a Unix timestamp.
    pub exp: usize, // Expiration time
    /// The groups the identity provider put the user in, as its verified ID token said
    /// at login (or the last refresh). Policy grants admin and author rights by them.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub groups: Vec<String>,
}

impl Claims {
    /// The user these claims identify, as policy sees them.
    pub fn opa_subject(&self) -> OpaSubject<'_> {
        OpaSubject {
            sub: &self.sub,
            email: self.email.as_deref(),
            groups: &self.groups,
        }
    }
}

/// Context for OPA checks in the API
#[derive(Debug, Serialize)]
pub struct ApiOpaContext<'a> {
    /// The requested path.
    pub path: &'a str,
    /// The HTTP method.
    pub method: &'a str,
    /// Who is asking, as their verified token says. `None` without a valid token.
    pub subject: Option<OpaSubject<'a>>,
}

/// Context for OPA checks in the Engine after DSL parsing
#[derive(Debug, Serialize)]
pub struct EngineOpaContext {
    /// Associated workflow run ID.
    pub run_id: RunId,
    /// Identifier of the user who initiated the run.
    pub initiating_user: String,
    /// Full parsed abstract syntax tree of the workflow.
    pub workflow_ast: Value,
    /// JSON inputs for the workflow run.
    pub inputs: Value,
}
/// Context for OPA checks during HITL Approvals
#[derive(Debug, Serialize)]
pub struct ApprovalOpaContext<'a> {
    /// Associated workflow run ID.
    pub run_id: RunId,
    /// Identifier of the user who initiated the run.
    pub initiating_user: String,
    /// The parsed abstract syntax tree of the approval step.
    pub step_ast: Value,
    /// JSON inputs for the workflow run.
    pub inputs: Value,
    /// All outputs generated by previous steps in the run.
    pub run_outputs: Value,
    /// The approver's verified identity, when they are logged in.
    pub approver: Option<OpaSubject<'a>>,
}

/// A user as policy sees them: the identity the API verified from their token.
#[derive(Debug, Clone, Copy, Serialize)]
pub struct OpaSubject<'a> {
    /// Subject (user id) of the token.
    pub sub: &'a str,
    /// Email address, when the token carries one.
    pub email: Option<&'a str>,
    /// The identity provider's groups, as the token carries them.
    pub groups: &'a [String],
}

/// The object a resource check is about.
#[derive(Debug, Clone, Copy, Serialize)]
pub struct OpaResource<'a> {
    /// `run`, `connection`, `webhook`, `event_rule` or `cron_workflow`.
    #[serde(rename = "type")]
    pub kind: &'a str,
    /// The object's id, or its name where that is how it is referred to.
    pub id: &'a str,
    /// Who created it (for a run, who started it). `None` for objects that predate
    /// ownership.
    pub owner: Option<&'a str>,
}

/// Context for OPA checks on one object: may `subject` do `action` to `resource`?
#[derive(Debug, Serialize)]
pub struct ResourceOpaContext<'a> {
    /// `read`, `update`, `delete` or `use`.
    pub action: &'a str,
    /// The object acted on, with its owner.
    pub resource: OpaResource<'a>,
    /// Who is acting.
    pub subject: OpaSubject<'a>,
}

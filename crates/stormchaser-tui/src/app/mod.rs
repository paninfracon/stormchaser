/// A summary of a workflow run, used for list views.
#[derive(Debug, Serialize, Deserialize, Clone)]
pub struct WorkflowRunDetail {
    /// Unique identifier for the run.
    pub id: RunId,
    /// Name of the workflow.
    pub workflow_name: String,
    /// The user who initiated the run.
    pub initiating_user: String,
    /// The current status of the run.
    pub status: RunStatus,
    /// The time the run was created.
    pub created_at: DateTime<Utc>,
    /// The time the run finished, if it has completed.
    pub finished_at: Option<DateTime<Utc>>,
}

/// Detailed information about a single step within a workflow run.
#[derive(Debug, Serialize, Deserialize, Clone)]
pub struct StepDetail {
    /// The step instance data.
    pub instance: Value,
    /// The outputs produced by the step.
    pub outputs: Vec<Value>,
    /// The execution history of the step.
    pub history: Vec<Value>,
    /// The logs generated by the step.
    pub logs: Vec<String>,
}

/// Comprehensive details of a workflow run, including its steps and artifacts.
#[derive(Debug, Serialize, Deserialize, Clone)]
pub struct WorkflowRunFullDetail {
    /// The summary details of the run.
    pub detail: WorkflowRunDetail,
    /// The detailed information for each step in the run.
    pub steps: Vec<StepDetail>,
    /// Artifacts generated during the run.
    pub artifacts: Vec<connections::ArtifactRegistry>,
    /// Test summaries generated during the run.
    pub test_summaries: Vec<test_report::TestSummary>,
    /// Individual test cases executed during the run.
    pub test_cases: Vec<test_report::TestCase>,
}

/// Request payload for exchanging an SSO token for access tokens.
#[derive(Debug, Serialize, Deserialize)]
pub struct AuthExchangeRequest {
    /// The single sign-on token to exchange.
    pub sso_token: String,
    /// The callback URL used during the OAuth flow.
    pub callback_url: String,
}

/// Response payload containing access and refresh tokens after successful authentication.
#[derive(Debug, Serialize, Deserialize)]
pub struct AuthExchangeResponse {
    /// The access token for authenticating API requests.
    pub access_token: String,
    /// An optional token used to refresh the access token.
    pub refresh_token: Option<String>,
}

/// Represents the current authentication state of the application.
#[derive(Debug, PartialEq, Eq, Clone, Copy)]
pub enum AppState {
    /// The user is not currently logged in.
    LoggedOut,
    /// A login attempt is currently in progress.
    LoggingIn,
    /// The user is successfully logged in.
    LoggedIn,
}

/// Represents the currently active pane in the user interface.
#[derive(Debug, PartialEq, Eq, Clone, Copy)]
pub enum Pane {
    /// The pane displaying the list of workflow runs.
    RunsList,
    /// The pane displaying detailed information for a selected run.
    RunDetail,
    /// The pane displaying test results for a selected run.
    TestResults,
    /// The pane displaying the list of storage backends.
    ConnectionsList,
    /// The pane displaying detailed information for a selected storage backend.
    ConnectionDetail,
    /// The pane displaying the list of webhooks.
    WebhooksList,
    /// The pane displaying detailed information for a selected webhook.
    WebhookDetail,
    /// The pane displaying the list of event rules.
    EventRulesList,
    /// The pane displaying detailed information for a selected event rule.
    EventRuleDetail,
    /// The pane displaying the list of cron workflows.
    CronWorkflowsList,
    /// The pane displaying detailed information for a selected cron workflow.
    CronWorkflowDetail,
}


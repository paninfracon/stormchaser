impl<'a> App<'a> {
    /// Creates a new instance of the TUI application state.
    pub fn new(
        url: String,
        query_url: String,
        token: Option<String>,
        status_tx: mpsc::Sender<AppEvent>,
    ) -> Self {
        let mut auto_login_credentials = Vec::new();
        if let Ok(content) = std::fs::read_to_string("deploy/dex/credentials.generated") {
            for line in content.lines() {
                if let Some((email, password)) = line.split_once(": ") {
                    if email.contains('@') {
                        auto_login_credentials
                            .push((email.trim().to_string(), password.trim().to_string()));
                    }
                }
            }
        }

        let state = if token.is_some() {
            AppState::LoggedIn
        } else {
            AppState::LoggedOut
        };

        Self {
            url,
            query_url,
            state,
            token,
            refresh_token: None,
            filter_owner: None,
            filter_name: None,
            filter_repo_url: None,
            filter_workflow_path: None,
            filter_created_after: None,
            filter_created_before: None,
            filter_status: None,
            runs: Vec::new(),
            runs_state: ListState::default(),
            selected_run: None,
            connections: Vec::new(),
            connections_state: ListState::default(),
            selected_connection: None,
            webhooks: Vec::new(),
            webhooks_state: ListState::default(),
            selected_webhook: None,
            event_rules: Vec::new(),
            event_rules_state: ListState::default(),
            selected_event_rule: None,
            cron_workflows: Vec::new(),
            cron_workflows_state: ListState::default(),
            selected_cron_workflow: None,
            selected_step_index: 0,
            run_logs: Vec::new(),
            log_scroll: 0,
            log_scroll_x: 0,
            log_auto_scroll: true,
            overview_scroll: 0,
            active_pane: Pane::RunsList,
            error: None,
            render_time: None,
            last_refresh_time: None,
            status_tx,
            watcher_handle: None,
            force_select_run_id: None,
            log_handle: None,
            workflow_handle: None,
            filter_dialog_active: false,
            filter_focus: 0,
            filter_inputs: Vec::new(),
            filter_status_index: 0,
            schedule_git_dialog_active: false,
            schedule_git_focus: 0,
            schedule_git_inputs: Vec::new(),
            connection_dialog_active: false,
            connection_focus: 0,
            connection_inputs: Vec::new(),
            connection_type_index: 0,
            connection_is_default: false,
            connection_edit_id: None,
            webhook_dialog_active: false,
            webhook_focus: 0,
            webhook_inputs: Vec::new(),
            webhook_source_type_index: 0,
            webhook_is_active: false,
            webhook_edit_id: None,
            event_rule_dialog_active: false,
            event_rule_focus: 0,
            event_rule_inputs: Vec::new(),
            event_rule_is_active: false,
            event_rule_edit_id: None,
            cron_dialog_active: false,
            cron_focus: 0,
            cron_inputs: Vec::new(),
            cron_is_active: false,
            cron_edit_id: None,
            approval_dialog_active: false,
            delete_run_dialog_active: false,
            approval_inputs: TextArea::default(),
            file_browser_active: false,
            pending_schema_ui: None,
            direct_submit_dsl: None,
            auto_login_credentials,
            auto_login_index: 0,
            cached_runs: HashMap::new(),
            fetched_steps: std::collections::HashSet::new(),
            file_explorer: tui_file_explorer::FileExplorer::new(
                std::env::current_dir().unwrap_or_default(),
                vec!["storm".to_string()],
            ),
            _marker: PhantomData,
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use tokio::sync::mpsc;

    #[test]
    fn test_app_new() {
        let (tx, _rx) = mpsc::channel(1);
        let app = App::new(
            "http://test".to_string(),
            "http://test:3001".to_string(),
            Some("token".to_string()),
            tx,
        );

        assert_eq!(app.url, "http://test");
        assert_eq!(app.query_url, "http://test:3001");
        assert_eq!(app.token, Some("token".to_string()));
        assert_eq!(app.state, AppState::LoggedIn);
        assert_eq!(app.active_pane, Pane::RunsList);
        assert!(app.run_logs.is_empty());
        assert_eq!(app.runs.len(), 0);
    }
}
